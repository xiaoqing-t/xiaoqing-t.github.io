import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const TEMPLATE = `${root}public/resume.html`
const OUTPUT = `${root}public/resume-en.html`
const DICT = `${root}scripts/resume-en.json`
const CJK = /[\u3400-\u9fff]/
const BLOCK = /<(h[123]|p|li|span)\b([^>]*)>([\s\S]*?)<\/\1>/g
const normalize = (text) => text.trim().replace(/\s+/g, ' ')

const template = readFileSync(TEMPLATE, 'utf8')
const main = template.match(/<main class="resume container">([\s\S]*?)<\/main>/)
if (!main) throw new Error('public/resume.html 里找不到 <main class="resume container">')

const rawDict = JSON.parse(readFileSync(DICT, 'utf8'))
const dict = Object.fromEntries(Object.entries(rawDict).map(([key, value]) => [normalize(key), value]))
const missing = []
let translatedCount = 0

const translatedMain = main[1].replace(BLOCK, (full, tag, attrs, inner) => {
  const key = normalize(inner)
  if (!CJK.test(key)) return full
  if (!Object.prototype.hasOwnProperty.call(dict, key)) {
    missing.push(key)
    return full
  }
  translatedCount += 1
  return `<${tag}${attrs}>${dict[key]}</${tag}>`
})

if (missing.length > 0) {
  console.error(`[resume] 中文简历改过，但有 ${missing.length} 段还没有英文译文：`)
  for (const text of missing) {
    console.error(`  · ${text.replace(/\s+/g, ' ').slice(0, 160)}`)
  }
  console.error('[resume] 把新句子补进 scripts/resume-en.json 后重跑 npm run sync:resume')
  process.exit(1)
}

const enNav = `  <nav class="nav no-print" id="nav">
    <div class="nav-inner">
      <a class="nav-brand" href="index.html">ZY <span class="nav-brand-en">/ Back to home</span></a>
      <div class="resume-nav-actions">
        <a class="btn-print" href="resume.html">中文</a>
        <button class="btn-print" onclick="window.print()">Print / Save as PDF</button>
      </div>
    </div>
  </nav>`

let page = template
  .replace('<html lang="zh-CN">', '<html lang="en">')
  .replace(/<title>[\s\S]*?<\/title>/, '<title>Résumé · Zhao Yunzhe</title>')
  .replace(
    /<meta name="description"[^>]*>/,
    '<meta name="description" content="Zhao Yunzhe — résumé. Computer science, deep learning, brain-computer interfaces, and AI engineering." />',
  )
  .replace(/<nav class="nav no-print" id="nav">[\s\S]*?<\/nav>/, enNav)
  .replace(/<main class="resume container">[\s\S]*?<\/main>/, `<main class="resume container">${translatedMain}</main>`)

page = page.replace(/<!--[\s\S]*?-->\s*/g, '')
page = page.replace(
  '<!DOCTYPE html>',
  '<!DOCTYPE html>\n<!-- Generated by scripts/resume-sync.mjs from public/resume.html. Do not edit. -->',
)

writeFileSync(OUTPUT, page)
console.log(`[resume] 写入 public/resume-en.html（${translatedCount} 个译文块）`)
